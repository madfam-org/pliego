// Whitespace-only archival normalization; retain every parsed JSON value.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,existsSync,mkdirSync} from 'node:fs';
import {resolve,join,basename} from 'node:path';
import {createHash} from 'node:crypto';
const [inputDirectory,outputDirectory,...names]=process.argv.slice(2);
assert.ok(inputDirectory&&outputDirectory&&names.length,'input directory, output directory and nonempty file list required');
const sha=b=>createHash('sha256').update(b).digest('hex');
mkdirSync(outputDirectory,{recursive:true});
const records=[];
for(const name of names){
  assert.equal(name,basename(name),'plain filenames only');
  const raw=readFileSync(join(inputDirectory,name)),value=JSON.parse(raw);
  assert.equal(value.schema,'pliego-plane-stress-audit/0.1');
  assert.equal(value.source.dirty,false);assert.equal(value.gates.sourceClean,true);
  const compact=Buffer.from(JSON.stringify(value)+'\n');
  assert.deepEqual(JSON.parse(compact),value,'all values/fields must survive archival normalization');
  const path=resolve(outputDirectory,name);assert.ok(!existsSync(path),'refuse existing archived file');
  writeFileSync(path,compact);
  records.push({file:name,originalSHA256:sha(raw),archivedSHA256:sha(compact),originalBytes:raw.length,archivedBytes:compact.length,allJSONValuesExact:true});
}
const manifest=join(outputDirectory,'archive-manifest.json');assert.ok(!existsSync(manifest),'refuse existing manifest');
writeFileSync(manifest,JSON.stringify({schema:'pliego-plane-stress-archive/0.1',node:process.version,toolSHA256:sha(readFileSync(new URL(import.meta.url))),
  normalization:'JSON.parse then JSON.stringify without indentation plus final newline; every parsed field/value and array/key order retained; original reports were generated by the same JSON.stringify; comparisons are rerun against archived bytes',records},null,2)+'\n');
console.log('plane-stress-archive: '+records.length+' complete reports; every JSON value exact; original/archived hashes retained');
